#!/usr/bin/env python3
"""Generate docs/CODEMAP.md from the code itself.

The map lists every module's public classes, functions, HTTP routes, exported
TypeScript names and state machines. Because it is derived from the source it
cannot go stale the way a hand-written description does.

    python3 scripts/codemap.py           write docs/CODEMAP.md
    python3 scripts/codemap.py --check   exit 1 if the file is out of date (CI)

State machines: any module-level `TRANSITIONS = {State.A: {State.B}, ...}` is
drawn as a Mermaid state diagram, so reviewers read the machine, not the code.
"""

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "CODEMAP.md"
SKIP_DIRS = {
    ".git", ".venv", "venv", "node_modules", ".next", "dist", "build", "__pycache__",
    ".claude", ".cursor", ".github", "docs", "tests", "lint-rules", "scripts",
}
HTTP_METHODS = {"get", "post", "put", "patch", "delete"}
WEB_SUFFIXES = {".ts", ".tsx"}
TS_EXPORT = re.compile(
    r"^export\s+(?:default\s+)?(?:async\s+)?(?:function|const|class|type|interface|enum)\s+([A-Za-z_]\w*)",
    re.MULTILINE,
)
HEADER = (
    "# Code map\n\n"
    "<!-- Generated by scripts/codemap.py from the source. Do not edit by hand. -->\n"
)


def source_files(suffixes: set[str]) -> list[Path]:
    files = []
    for path in ROOT.rglob("*"):
        relative = path.relative_to(ROOT)
        if any(part in SKIP_DIRS for part in relative.parts):
            continue
        if path.is_file() and path.suffix in suffixes and not path.name.startswith("test_"):
            files.append(path)
    return sorted(files)


def first_line(text: str | None) -> str:
    return text.strip().splitlines()[0] if text and text.strip() else ""


def is_public(name: str) -> bool:
    return not name.startswith("_")


def state_name(node: ast.expr) -> str | None:
    """`State.RUNNING` -> RUNNING; "running" -> running."""
    if isinstance(node, ast.Attribute):
        return node.attr
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def target_states(node: ast.expr) -> list[str]:
    """States listed in a set, list or tuple, or wrapped in frozenset(...) / set(...)."""
    if isinstance(node, ast.Call) and node.args:
        node = node.args[0]
    if isinstance(node, (ast.Set, ast.List, ast.Tuple)):
        return [name for element in node.elts if (name := state_name(element))]
    return []


def statechart(table: ast.Dict) -> list[str]:
    rows = [(state_name(key), target_states(value)) for key, value in zip(table.keys, table.values) if key]
    rows = [(source, targets) for source, targets in rows if source]
    if not rows:
        return []
    lines = ["", "```mermaid", "stateDiagram-v2", f"    [*] --> {rows[0][0]}"]
    for source, targets in rows:
        if not targets:
            lines.append(f"    {source} --> [*]")
        lines.extend(f"    {source} --> {target}" for target in targets)
    lines.extend(["```", ""])
    return lines


def routes(function: ast.FunctionDef | ast.AsyncFunctionDef) -> list[str]:
    found = []
    for decorator in function.decorator_list:
        if not (isinstance(decorator, ast.Call) and isinstance(decorator.func, ast.Attribute)):
            continue
        method = decorator.func.attr
        has_path = decorator.args and isinstance(decorator.args[0], ast.Constant)
        if method in HTTP_METHODS and has_path:
            found.append(f"- route `{method.upper()} {decorator.args[0].value}` -> `{function.name}`")
    return found


def describe_class(node: ast.ClassDef) -> str:
    bases = [ast.unparse(base) for base in node.bases]
    if any("Enum" in base for base in bases):
        members = [
            target.id
            for statement in node.body
            if isinstance(statement, ast.Assign)
            for target in statement.targets
            if isinstance(target, ast.Name)
        ]
        return f"- enum `{node.name}`: {', '.join(members)}"
    signature = f"{node.name}({', '.join(bases)})" if bases else node.name
    summary = first_line(ast.get_docstring(node))
    return f"- class `{signature}`" + (f" - {summary}" if summary else "")


def describe_function(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    summary = first_line(ast.get_docstring(node))
    return f"- `{node.name}({ast.unparse(node.args)}){returns}`" + (f" - {summary}" if summary else "")


def describe_python(path: Path) -> list[str]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except SyntaxError:
        return ["- (syntax error: could not be parsed)"]

    lines: list[str] = []
    summary = first_line(ast.get_docstring(tree))
    if summary:
        lines.extend([summary, ""])

    for node in tree.body:
        if isinstance(node, ast.ClassDef) and is_public(node.name):
            lines.append(describe_class(node))
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and is_public(node.name):
            lines.extend(routes(node) or [describe_function(node)])
        elif isinstance(node, (ast.Assign, ast.AnnAssign)) and isinstance(node.value, ast.Dict):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            if any(isinstance(target, ast.Name) and target.id == "TRANSITIONS" for target in targets):
                lines.extend(statechart(node.value))
    return lines


def describe_web(path: Path) -> list[str]:
    names = sorted(set(TS_EXPORT.findall(path.read_text(encoding="utf-8", errors="ignore"))))
    return [f"- exports: {', '.join(f'`{name}`' for name in names)}"] if names else []


def render() -> str:
    sections: list[str] = []
    for path in source_files({".py"} | WEB_SUFFIXES):
        body = describe_python(path) if path.suffix == ".py" else describe_web(path)
        if body:
            sections.append(f"## `{path.relative_to(ROOT).as_posix()}`\n\n" + "\n".join(body).strip() + "\n")
    if not sections:
        return HEADER + "\nNo source files yet.\n"
    return HEADER + "\n" + "\n".join(sections)


def main() -> int:
    rendered = render()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None

    if "--check" in sys.argv:
        if current != rendered:
            print("docs/CODEMAP.md is stale. Run: python3 scripts/codemap.py")
            return 1
        print("docs/CODEMAP.md is up to date.")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({rendered.count(chr(10) + '## ')} modules).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
